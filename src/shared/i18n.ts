const DICTS: Record<UiLang, Dict> = { ru, en };

export function t(lang: UiLang, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? ru;
  let out = dict[key] ?? ru[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) out = out.replaceAll(`{${name}}`, String(value));
  }
  return out;
}

/** Human-readable error for a provider failure code. */
export function errorText(lang: UiLang, code: string, fallback: string): string {
  const dict = DICTS[lang] ?? ru;
  return dict[`error.${code}`] ?? fallback;
}
